#!/bin/bash
# Release build of outbox-exec and assembly of exec/build/OutboxExec.app, ad-hoc signed with the hardened runtime.
# Run with the Bash sandbox off (swift and codesign write outside the working directory).
#
# Every rebuild changes the code hash, so macOS drops the executor's Automation (Messages) and Contacts grants:
# approve the two prompts again the next time the executor needs them. That is deliberate (ARCHITECTURE section 10).
set -euo pipefail
cd "$(dirname "$0")"
HERE="$PWD"
REPO="$(cd .. && pwd)"
APP="$HERE/build/OutboxExec.app"
BUNDLE_ID="io.github.ay2609.agent-outbox.exec"
VERSION="$(sed -n 's/.*static let current = "\(.*\)".*/\1/p' Sources/OutboxExecCore/Util.swift)"
[ -n "$VERSION" ] || { echo "cannot read version from Util.swift" >&2; exit 1; }

echo "== embedding src/db/schema.sql into the selftest ($REPO/src/db/schema.sql)"
{
  echo '// GENERATED by exec/build.sh from src/db/schema.sql. Do not edit.'
  echo 'public enum EmbeddedSchema {'
  echo '    public static let sql = #"""'
  cat "$REPO/src/db/schema.sql"
  echo '"""#'
  echo '}'
} > Sources/OutboxExecCore/EmbeddedSchema.swift

echo "== swift build -c release"
set +o pipefail
swift build -c release 2>&1 | grep -v '^\[' | grep -v 'persisted-output'
status=${PIPESTATUS[0]}
set -o pipefail
[ "$status" -eq 0 ] || { echo "swift build failed (exit $status); not assembling a stale app" >&2; exit "$status"; }
BIN="$(swift build -c release --show-bin-path)/outbox-exec"
[ -x "$BIN" ] || { echo "release binary not found at $BIN" >&2; exit 1; }

echo "== assembling $APP"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS"
cp "$BIN" "$APP/Contents/MacOS/outbox-exec"
cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
	<key>CFBundleName</key><string>Agent Outbox</string>
	<key>CFBundleDisplayName</key><string>Agent Outbox</string>
	<key>CFBundleExecutable</key><string>outbox-exec</string>
	<key>CFBundlePackageType</key><string>APPL</string>
	<key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
	<key>CFBundleShortVersionString</key><string>$VERSION</string>
	<key>CFBundleVersion</key><string>$VERSION</string>
	<key>LSMinimumSystemVersion</key><string>13.0</string>
	<key>LSUIElement</key><true/>
	<key>NSAppleEventsUsageDescription</key><string>Agent Outbox sends the iMessages you approved in the agent-outbox dashboard through Messages.</string>
	<key>NSContactsUsageDescription</key><string>Agent Outbox reads your contacts for the agent-outbox dashboard and adds contacts you approved.</string>
</dict>
</plist>
PLIST
plutil -lint "$APP/Contents/Info.plist"
plutil -lint "$HERE/entitlements.plist"

echo "== codesign (ad-hoc, hardened runtime)"
codesign --force -s - --options runtime --identifier "$BUNDLE_ID" --entitlements "$HERE/entitlements.plist" "$APP"
codesign -dv --verbose=4 "$APP" 2>&1 | grep -E 'Identifier|Format|CodeDirectory|flags|Signature|Authority|TeamIdentifier|CDHash|Info.plist|Sealed' || true
codesign --verify --strict --verbose=2 "$APP"
echo "-- entitlements:"
codesign -d --entitlements - "$APP" 2>/dev/null | grep -E 'apple-events|addressbook' || true
echo "== built $APP (version $VERSION)"
echo "   run the tests:  $APP/Contents/MacOS/outbox-exec selftest"
